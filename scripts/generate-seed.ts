/**
 * Generates supabase/seed.sql from the TypeScript seed data so the database
 * and the preview mode always start from the same content.
 * Run: npm run db:seed:generate
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { SEED_CROPS } from "../src/data/crops";
import { SEED_FAQS } from "../src/data/faqs";
import { COUNTRIES, REGIONS } from "../src/data/regions";
import { DEFAULT_THRESHOLDS } from "../src/domain/weather";

const q = (v: string | null | undefined) => (v == null || v === "" ? "null" : `'${v.replace(/'/g, "''")}'`);
const n = (v: number | null | undefined) => (v == null ? "null" : String(v));
const arr = (v: (string | number)[] | undefined, type: "text" | "int") =>
  !v || v.length === 0 ? `'{}'::${type}[]` : `array[${v.map((x) => (type === "text" ? q(String(x)) : String(x))).join(",")}]::${type}[]`;

const lines: string[] = [
  "-- Generated by scripts/generate-seed.ts — do not edit by hand.",
  "-- Preliminary content: review with a local agronomist before relying on it.",
  "begin;",
  "",
];

COUNTRIES.forEach((c, i) => {
  lines.push(`insert into public.countries (code, name, sort_order) values (${q(c.code)}, ${q(c.name)}, ${i}) on conflict (code) do update set name = excluded.name;`);
});
lines.push("");
REGIONS.forEach((r, i) => {
  lines.push(
    `insert into public.regions (id, country_code, name, zone, latitude, longitude, timezone, sort_order) values (${q(r.id)}, ${q(r.countryCode)}, ${q(r.name)}, ${q(r.zone)}, ${r.latitude}, ${r.longitude}, ${q(r.timezone)}, ${i}) on conflict (id) do nothing;`,
  );
});
lines.push("");

for (const c of SEED_CROPS) {
  lines.push(`-- ${c.slug}`);
  // New crops are inserted; existing rows keep every admin edit and only gain
  // new search aliases (merged, never removed or duplicated) and, when still
  // empty, the propagation list.
  lines.push(
    `insert into public.crops (slug, name, other_names, scientific_name, category, life_cycle, difficulty, sun, water, frost_sensitive, space_types, growth_days_min, growth_days_max, growth_note, summary, watering_summary, image_alt, data_status, source_note, propagation) values (${q(c.slug)}, ${q(c.name)}, ${arr(c.otherNames, "text")}, ${q(c.scientificName)}, ${q(c.category)}, ${q(c.lifeCycle)}, ${q(c.difficulty)}, ${q(c.sun)}, ${q(c.water)}, ${c.frostSensitive}, ${arr(c.spaceTypes, "text")}, ${n(c.growthDaysMin)}, ${n(c.growthDaysMax)}, ${q(c.growthNote)}, ${q(c.summary)}, ${q(c.wateringSummary)}, ${q(c.imageAlt)}, ${q(c.dataStatus)}, ${q(c.sourceNote)}, ${arr(c.propagation, "text")}) on conflict (slug) do update set other_names = (public.crops.other_names || array(select x from unnest(excluded.other_names) as u(x) where not (x = any(public.crops.other_names))))[1:12], propagation = case when cardinality(public.crops.propagation) = 0 then excluded.propagation else public.crops.propagation end;`,
  );
  const crop = `(select id from public.crops where slug = ${q(c.slug)})`;
  c.windows.forEach((w, i) => {
    lines.push(
      `insert into public.crop_planting_windows (crop_id, zone, start_month, end_month, method, note, sort_order) select ${crop}, ${q(w.zone)}, ${w.startMonth}, ${w.endMonth}, ${q(w.method)}, ${q(w.note)}, ${i} where not exists (select 1 from public.crop_planting_windows x where x.crop_id = ${crop} and x.sort_order = ${i});`,
    );
  });
  c.templates.forEach((t, i) => {
    lines.push(
      `insert into public.crop_task_templates (crop_id, key, type, title, description, offset_days, repeat_every_days, until_offset_days, active_months, sort_order) values (${crop}, ${q(t.key)}, ${q(t.type)}, ${q(t.title)}, ${q(t.description)}, ${t.offsetDays}, ${n(t.repeatEveryDays)}, ${n(t.untilOffsetDays)}, ${arr(t.activeMonths, "int")}, ${i}) on conflict (crop_id, key) do nothing;`,
    );
  });
  c.guide.forEach((g, i) => {
    lines.push(
      `insert into public.crop_guides (crop_id, section, title, body, sort_order) select ${crop}, ${q(g.section)}, ${q(g.title)}, ${q(g.body)}, ${i} where not exists (select 1 from public.crop_guides x where x.crop_id = ${crop} and x.section = ${q(g.section)});`,
    );
  });
  lines.push("");
}

SEED_FAQS.forEach((f, i) => {
  lines.push(
    `insert into public.faqs (question, answer, sort_order) select ${q(f.question)}, ${q(f.answer)}, ${i} where not exists (select 1 from public.faqs where question = ${q(f.question)});`,
  );
});
lines.push("");
lines.push(
  `insert into public.site_settings (key, value) values ('weather_thresholds', '${JSON.stringify(DEFAULT_THRESHOLDS)}'::jsonb) on conflict (key) do nothing;`,
);
lines.push(`insert into public.site_settings (key, value) values ('contact', '{"email": ""}'::jsonb) on conflict (key) do nothing;`);
lines.push("", "commit;", "");

const out = join(process.cwd(), "supabase", "seed.sql");
writeFileSync(out, lines.join("\n"), "utf8");
console.log(`Wrote ${out}`);
