function once(key: string, type: TaskType, offsetDays: number, title: string, description: string): TaskTemplate {
  return { key, type, offsetDays, title, description };
}

function every(
  key: string,
  type: TaskType,
  from: number,
  until: number,
  interval: number,
  title: string,
  description: string,
  activeMonths?: number[],
): TaskTemplate {
  return { key, type, offsetDays: from, untilOffsetDays: until, repeatEveryDays: interval, title, description, activeMonths };
}

